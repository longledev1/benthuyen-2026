-- 1. Tạo bảng lưu trữ thông tin đặt bàn của khách hàng
CREATE TABLE IF NOT EXISTS public.table_bookings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    name text NOT NULL,
    phone text NOT NULL,
    time_slot text NOT NULL,
    guest_count integer NOT NULL,
    area text NOT NULL,
    vip_room_name text,
    status text DEFAULT 'pending'::text NOT NULL,
    note text DEFAULT ''::text NOT NULL
);

-- 2. Kích hoạt Row Level Security (RLS) để bảo mật dữ liệu
ALTER TABLE public.table_bookings ENABLE ROW LEVEL SECURITY;

-- 3. Tạo chính sách (Policy) cho phép BẤT KỲ AI (Public) cũng có thể gửi yêu cầu đặt bàn (Insert)
CREATE POLICY "Cho phép khách đặt bàn" 
ON public.table_bookings 
FOR INSERT 
TO public 
WITH CHECK (true);

-- 4. Tạo chính sách cho phép đọc (Select) và cập nhật (Update) thông tin đặt bàn
CREATE POLICY "Cho phép quản trị viên xem đặt bàn" 
ON public.table_bookings 
FOR SELECT 
TO public 
USING (true);

CREATE POLICY "Cho phép quản trị viên cập nhật đặt bàn" 
ON public.table_bookings 
FOR UPDATE 
TO public 
USING (true)
WITH CHECK (true);
